// Embeds the single-file plugin build (preview/index.html) into the test bench as a JS string,
// escaped so it can sit inside an inline <script> safely.
import { readFileSync, writeFileSync } from 'node:fs';
const html = readFileSync(new URL('../preview/index.html', import.meta.url), 'utf8');
const literal = JSON.stringify(html).replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');
writeFileSync(new URL('../src/harness/pluginHtml.generated.js', import.meta.url),
  `// Generated by scripts/embed-plugin.mjs from preview/index.html. Do not edit.\nexport default ${literal};\n`);
console.log('embedded plugin build:', html.length, 'chars');
